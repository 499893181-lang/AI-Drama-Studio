import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createStudio } from '../src/server.mjs';
import { fixtureEntities, fixtureShots } from './creative-fixtures.mjs';
import { testPng } from './image-fixtures.mjs';

const artifacts = path.resolve('tests/.artifacts'); fs.mkdirSync(artifacts, { recursive: true });
test('图片HTTP往返、错误上传元信息、项目隔离及真实参考ZIP；不会调用模型', async t => {
  const app = createStudio({ dataDir: fs.mkdtempSync(path.join(artifacts, 'image-http-')), inspectImageTools: async () => ({ checkedAt: new Date().toISOString(), mode: 'manual_export_import', automaticSubmissionEnabled: false }) });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(() => app.close());
  const base = `http://127.0.0.1:${app.server.address().port}`;
  const project = app.store.create({ name: '[测试] 图片HTTP', idea: '仅用于软件图片上传与恢复验证，非真实AI结果。' });
  app.creative.update(project.id, { revision: 0, entities: structuredClone(fixtureEntities), shots: fixtureShots() });
  app.creative.addVersion(project.id, { revision: 1, kind: 'storyboard', body: '【人工软件测试分镜】3镜头。' });
  const route = `/api/projects/${project.id}/images`;
  const get = async () => (await fetch(base + route)).json();
  const post = async (suffix, value) => {
    const response = await fetch(base + route + suffix, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(value) });
    assert.ok(response.ok, await response.clone().text()); return response.json();
  };
  let response = await fetch(base + route + '/import', { method: 'POST', headers: { 'x-image-metadata': '%BAD', 'Content-Type': 'image/png' }, body: testPng() });
  assert.equal(response.status, 400);
  const state = await get();
  const metadata = { revision: state.revision, role: 'character', targetId: 'CHAR-01', filename: '../TEST-FIXTURE-NOT-AI.png', source: { kind: 'test', description: '像素标记TEST FIXTURE / NOT AI，软件测试。' } };
  const bytes = testPng();
  response = await fetch(base + route + '/import', { method: 'POST', headers: { 'x-image-metadata': encodeURIComponent(JSON.stringify(metadata)), 'Content-Type': 'text/plain' }, body: bytes });
  assert.equal(response.status, 201);
  let ws = await response.json(); const asset = ws.assets.at(-1);
  assert.equal(asset.sha256, createHash('sha256').update(bytes).digest('hex'));
  response = await fetch(base + asset.url);
  assert.equal(response.headers.get('content-type'), 'image/png');
  assert.ok(Buffer.from(await response.arrayBuffer()).equals(bytes));
  const other = app.store.create({ name: '[测试] 不同项目' });
  response = await fetch(`${base}/api/projects/${other.id}/image-assets/${asset.id}`);
  assert.equal(response.status, 404);
  response = await fetch(base + route + '/select', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://example.invalid' }, body: JSON.stringify({ revision: ws.revision, assetId: asset.id }) });
  assert.equal(response.status, 403);
  ws = await post('/review', { revision: ws.revision, assetId: asset.id, verdict: 'accepted', notes: '实际文件往返验证，非审美通过。' });
  ws = await post('/select', { revision: ws.revision, assetId: asset.id });
  const packet = await post('/prepare', { revision: ws.revision, shotId: 'SHOT-01', referenceAssetIds: [asset.id] });
  assert.equal(packet.submitted, false);
  assert.equal(packet.references[0].attached, false);
  assert.equal(packet.references[0].includedInBundle, true);
  response = await fetch(`${base}${route}/packets/${packet.id}/bundle`);
  assert.equal(response.status, 200); assert.equal(response.headers.get('content-type'), 'application/zip');
  const zip = Buffer.from(await response.arrayBuffer());
  assert.equal(zip.readUInt32LE(0), 0x04034b50);
  assert.ok(zip.includes(Buffer.from('manifest.json')));
  assert.ok(zip.includes(Buffer.from('prompt.txt')));
  assert.ok(zip.includes(bytes), 'ZIP必须实际含参考图字节，不能仅有引用清单');
  const capability = await (await fetch(base + '/api/images/capabilities')).json();
  assert.equal(capability.automaticSubmissionEnabled, false);
});
